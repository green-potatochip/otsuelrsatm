  assert.equal(await page.locator('#range-origin').inputValue(), 'camera');
  assert.equal(await page.locator('[data-layer="candidates"]').isChecked(), true);
  assert.equal(await page.locator('#scene').getAttribute('data-body-antenna-links'), '0');
  await page.locator('#range-origin').selectOption('antenna');
  const recentLinks = Number(await page.locator('#scene').getAttribute('data-body-antenna-links'));
  assert.ok(recentLinks > 0);
  assert.equal(Number(await page.locator('#scene').getAttribute('data-body-node-count')), recentLinks);
  assert.equal(Number(await page.locator('#scene').getAttribute('data-antenna-node-count')), recentLinks);
  // Check rendered connector endpoints against independently read log coordinates.
  const referenceLog = JSON.parse(gunzipSync(await readFile(new URL('../data/eee_03/overview.json.gz', import.meta.url))).toString());
  const geometryCheck = await page.evaluate(json => {
    const viewport = document.querySelector('#scene');
    const example = JSON.parse(viewport.dataset.bodyAntennaExample);
    const samples = json.bodyTrajectories.causal_uwb.length ? json.bodyTrajectories.causal_uwb : json.bodyTrajectories.optimized_uwb;
    let j = samples.findIndex(pose => pose.t >= example.t);
    if (j < 0) j = samples.length - 1;
    const next = samples[j], prev = samples[Math.max(0,j-1)];
    const a = next.t === prev.t ? 0 : Math.max(0, Math.min(1, (example.t-prev.t)/(next.t-prev.t)));
    const body = prev.p.map((value,i) => value+a*(next.p[i]-value));
    const event = json.rangeMetrics.find(event => Math.abs(event.t-example.t)<1e-8 && event.tagId===example.tagId && event.tag);
    return {bodyError: Math.max(...body.map((value,i) => Math.abs(value-example.body[i]))), antennaError: Math.max(...event.tag.map((value,i) => Math.abs(value-example.antenna[i])))};
  }, referenceLog);
  assert.ok(geometryCheck.bodyError < 1e-5, 'Rendered body node does not match the measurement-time body pose');
  assert.ok(geometryCheck.antennaError < 1e-5, 'Rendered antenna node does not match the logged range origin');
  await page.locator('#range-history').selectOption('cumulative');
  assert.ok(Number(await page.locator('#scene').getAttribute('data-body-antenna-links')) > recentLinks);
  await page.locator('#range-origin').selectOption('camera');
  assert.equal(await page.locator('#scene').getAttribute('data-body-antenna-links'), '0');
  assert.equal(await page.locator('#scene').getAttribute('data-body-node-count'), '0');
  await page.locator('#range-origin').selectOption('antenna');
  await page.locator('#range-history').selectOption('trail-5');
  const compact = await page.locator('.time-explanation').boundingBox();
  assert.ok(compact.width < 600 && compact.height < 400, 'Acquisition-time card is too large on desktop');
  await page.locator('.acquisition-explanation').screenshot({ path: output + '/desktop-timing.png', style: '.navbar,.skip-link { visibility:hidden!important; }' });
  assert.equal(await page.locator('.lab').count(), 0);
  const inhouse = page.locator('.sequence-result[data-result-sequence="inhouse_htp_01"]');
  assert.equal(await inhouse.locator('[data-method="vio"] b').textContent(), '0.254');
  assert.equal(await inhouse.locator('[data-method="loop"] b').textContent(), '0.086');
  assert.equal(await inhouse.locator('[data-method="optimized"] b').textContent(), '0.087');
  assert.equal(await inhouse.locator('.best').getAttribute('data-method'), 'loop');
  await page.locator('[data-camera-results="monocular"]').click();
  assert.equal(await page.locator('.sequence-result [data-replay]').count(), 0);
  assert.equal(await inhouse.locator('[data-method="vio"] b').textContent(), '0.400');
  assert.equal(await inhouse.locator('[data-method="causal"] b').textContent(), '0.235');
  assert.equal(await page.locator('.sequence-result').count(), 13);
  await page.locator('[data-camera-results="stereo"]').click();
  assert.equal(await page.locator('.sequence-result [data-replay]').count(), 13);
  await page.locator('#experiments').evaluate(element => element.scrollIntoView({ block: 'start', behavior: 'instant' }));
  await page.waitForFunction(() => document.querySelector('#nav-links a[href="#experiments"]').getAttribute('aria-current') === 'location');
  await page.locator('#all-sequence-results').screenshot({ path: output + '/desktop-metrics.png' });
  await inhouse.locator('[data-replay]').click();
  await page.waitForFunction(() => document.querySelector('#scene').dataset.ready === 'true' && document.querySelector('#scene').dataset.sequence === 'inhouse_htp_01');
  await page.locator('.sequence-result [data-replay="eee_03"]').click();
  await page.waitForFunction(() => document.querySelector('#scene').dataset.ready === 'true' && document.querySelector('#scene').dataset.sequence === 'eee_03');
  assert.equal(await page.locator('#method input[type="range"]').count(), 0);
  assert.equal(await page.locator('[data-robot-trajectory]').count(), 1);
  assert.equal(await page.locator('[data-uwb-anchor]').count(), 1);
  assert.equal(await page.locator('[data-range-status="selected"]').count(), 4);
  assert.equal(await page.locator('[data-range-status="rejected"]').count(), 3);
  assert.equal(await page.locator('.reweight-projection').count(), 1);
  assert.equal(await page.locator('.weight-comparison').count(), 1);
  assert.match(await page.locator('.direction-explanation').textContent(), /Clear D after this admission/);
  assert.match(await page.locator('[data-admission="information"] .retention-ring').getAttribute('aria-label'), /35.5 percent/);
  assert.match(await page.locator('[data-admission="information"] .ablation-runtime').textContent(), /0.784.*56.4% lower/s);
  await page.locator('#method').screenshot({ path: output + '/desktop-method.png', style: '.navbar,.skip-link { visibility: hidden !important; }' });
  await page.locator('.static-information').screenshot({ path: output + '/desktop-information.png', style: '.navbar,.skip-link { visibility: hidden !important; }' });
  await page.locator('.admission-dashboard').screenshot({ path: output + '/desktop-ablation.png', style: '.navbar,.skip-link { visibility: hidden !important; }' });
  await page.locator('[data-pipeline-step="2"]').click();
  assert.equal(await page.locator('[data-layer="candidates"]').isChecked(), true);
  await page.locator('[data-pipeline-step="3"]').click();
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await page.screenshot({ path: `${output}/desktop-full.png`, fullPage: true });
  await page.locator('#explore').scrollIntoViewIfNeeded();
  await page.locator('.explorer').screenshot({ path: `${output}/desktop-viewer.png` });

  await page.locator('[data-pipeline-step="1"]').click();
  assert.match(await page.locator('#anchor-count').textContent(), /^[1-9]/);
  assert.equal(await page.locator('[data-layer="vio"]').isChecked(), true);
  assert.equal(await page.locator('[data-layer="optimized"]').isChecked(), false);
  await page.locator('[data-pipeline-step="2"]').click();
  await page.waitForFunction(() => Number(document.querySelector('#scene').dataset.candidateLinks) > 0);
  assert.match(await page.locator('#event-state').textContent(), /Not selected/);
  await page.locator('#next-event').click();
  assert.match(await page.locator('#event-state').textContent(), /Accepted/);
  await page.locator('#range-origin').selectOption('camera');
  await page.locator('#range-history').selectOption('trail-5');
  await page.locator('[data-view="xy"]').click();
  await page.locator('.signal-details').evaluate(element => { element.open = true; });
  await page.locator('#timeline').click({ position: { x: 330, y: 55 } });
  await page.locator('[data-layer="features"]').check();
  assert.ok(Number(await page.locator('#scene').getAttribute('data-feature-points')) > 0);
  await page.locator('[data-pipeline-step="3"]').click();
  await page.locator('#scrubber').evaluate(input => {input.value=input.max;input.dispatchEvent(new Event('input',{bubbles:true}));});
  const end = Number(await page.locator('#scene').getAttribute('data-playhead'));
  await page.locator('#play').click();
  await page.waitForFunction(previous => {
    const current = Number(document.querySelector('#scene').dataset.playhead);
    return current > 0.2 && current < previous;
  }, end);
  await page.locator('#play').click();
  assert.equal(await page.locator('#play').getAttribute('aria-label'), 'Play experiment');

  const names = await page.locator('[data-viewer-sequence]').evaluateAll(buttons => buttons.map(button => button.dataset.viewerSequence));
  await page.locator('#range-origin').selectOption('antenna');
  for (const name of names) {
    await page.locator(`[data-viewer-sequence="${name}"]`).click();
    await page.waitForFunction(expected => {
      const scene = document.querySelector('#scene');
      return scene.dataset.ready === 'true' && scene.dataset.sequence === expected;
    }, name, { timeout: 45000 });
    const state = await page.locator('#scene').evaluate(element => ({ sequence: element.dataset.sequence, points: Number(element.dataset.trajectoryPoints), links: Number(element.dataset.rangeLinks), sensorLinks: Number(element.dataset.bodyAntennaLinks), time: Number(element.dataset.playhead) }));
    assert.ok(state.points > 50, `${name} has no trajectory`);
    assert.ok(state.links > 0, `${name} has no range geometry at default time`);
    assert.ok(state.sensorLinks > 0, `${name} has no body-to-antenna geometry`);
    snapshots.push(state);
  }
  // Rapid switching must never allow a stale load to overwrite the new sequence.
  await page.locator('[data-viewer-sequence="eee_01"]').click();
  await page.locator('[data-viewer-sequence="sbs_03"]').click();
  await page.waitForFunction(() => document.querySelector('#scene').dataset.ready === 'true' && document.querySelector('#scene').dataset.sequence === 'sbs_03');
  await page.locator('.signal-details').evaluate(element => { element.open = false; });
  await page.locator('.sequence-result [data-replay="eee_03"]').click();
  await page.waitForFunction(() => document.querySelector('#scene').dataset.ready === 'true' && document.querySelector('#scene').dataset.sequence === 'eee_03');
  await page.locator('[data-view="iso"]').click();
  await page.locator('#scene').scrollIntoViewIfNeeded();
  await page.locator('.explorer').screenshot({ path: `${output}/desktop-viewer-final.png` });

  // Classic assets and replay bundles must work at the standalone root too.
  await page.goto(`${origin}/`);
  await page.waitForFunction(() => document.querySelector('#scene').dataset.ready === 'true', { timeout: 45000 });
  assert.equal(await page.locator('#scene').getAttribute('data-sequence'), 'eee_03');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${origin}${previewPath}`);
  await page.waitForFunction(() => document.querySelector('#scene').dataset.ready === 'true', { timeout: 45000 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'Mobile document overflows horizontally');
  await page.locator('#nav-toggle').click();
  assert.equal(await page.locator('#nav-toggle').getAttribute('aria-expanded'), 'true');
  await page.locator('#nav-links a[href="#experiments"]').click();
  assert.equal(await page.locator('#nav-toggle').getAttribute('aria-expanded'), 'false');
  await page.locator('#all-sequence-results').scrollIntoViewIfNeeded();
  await page.locator('#all-sequence-results').screenshot({ path: `${output}/mobile-metrics.png` });
  assert.equal(await page.locator('.timing-compact').isVisible(), true);
  assert.equal(await page.locator('.timing-desktop').count(), 0);
  await page.locator('.time-explanation').screenshot({ path: `${output}/mobile-timing.png`, style: '.navbar,.skip-link { visibility: hidden !important; }' });
