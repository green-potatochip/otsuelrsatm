  assert.equal(await page.locator('#nav-links a').first().getAttribute('href'), '#abstract');
  assert.equal(await page.locator('.authors').textContent(), 'Anonymous');
  assert.equal(await page.locator('.scene-canvas').count(), 1);
  assert.equal(await page.locator('.story, [data-step], #step-action').count(), 0);
  assert.deepEqual(await page.locator('#range-history option').evaluateAll(options => options.map(x => x.value)), ['trail-5', 'cumulative']);
  assert.deepEqual(await page.locator('#range-origin option').evaluateAll(options => options.map(x => x.value)), ['antenna', 'camera']);
  assert.equal(await page.locator('#range-history').inputValue(), 'trail-5');
  assert.equal(await page.locator('#scene').getAttribute('data-grid-z'), '0');
  assert.equal(await page.locator('#scene').getAttribute('data-feature-color-mode'), 'axis-z');
  assert.equal(await page.locator('#scene').getAttribute('data-feature-vertex-colors'), 'true');
