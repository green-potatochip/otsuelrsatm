import { build } from 'vite';
import { mkdir, readFile, writeFile, copyFile, cp, access, readdir, unlink } from 'node:fs/promises';
import { resolve, join, sep, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';

const root = fileURLToPath(new URL('../', import.meta.url));
const data = resolve(root, 'data');
const manifest = JSON.parse(await readFile(join(data, 'manifest.json'), 'utf8'));
const paper = JSON.parse(await readFile(join(root, 'paper-metrics.json'), 'utf8'));
const results = [];
for (const entry of manifest.sequences) {
  const folder = resolve(data, entry.name);
  if (!folder.startsWith(data + sep)) throw new Error('Invalid sequence path: ' + entry.name);
  for (const file of ['manifest.json', 'overview.json.gz', 'features.optimized_uwb.json.gz']) await access(join(folder, file));
  const label = entry.name.startsWith('inhouse_') ? entry.name.replace('inhouse_', '') : entry.name;
  const index = paper.sequences.indexOf(label);
  if (index < 0) throw new Error('Missing paper results for ' + label);
  const values = mode => Object.fromEntries(['vio', 'loop', 'causal', 'optimized'].map(method => {
    const value = paper[mode][method][index];
    if (!Number.isFinite(value)) throw new Error('Invalid paper result');
    return [method, value];
  }));
  results.push({ sequence: entry.name, dataset: entry.name.startsWith('inhouse_') ? 'inhouse' : 'ntu', label, stereo: values('stereo'), monocular: values('monocular'), source: 'Submitted manuscript · Table III · page 7' });
}
await writeFile(join(data, 'results.json'), JSON.stringify(results));

const hash = bytes => createHash('sha256').update(bytes).digest('hex').slice(0, 12);
const scripts = {};
async function writeBundle(group, entries) {
  const folder = resolve(data, group || '.');
  if (folder !== data && !folder.startsWith(data + sep)) throw new Error('Invalid bundle path');
  const prefix = group ? 'replay-' : 'catalog-';
  // Only replace generated transport files in the explicitly resolved data folder.
  for (const name of await readdir(folder)) {
    if (new RegExp('^' + prefix + '[a-f0-9]{12}\\.js$').test(name)) await unlink(join(folder, name));
  }
  const content = '(function(){const files=globalThis.__OUR_SLAM_REPLAY__??=new Map();' +
    entries.map(([path, value]) => 'files.set(' + JSON.stringify(path) + ',' + JSON.stringify(value) + ');').join('') + '})();\n';
  if (Buffer.byteLength(content) >= 8 * 1024 * 1024) throw new Error('Replay file exceeds host limit: ' + group);
  const name = prefix + hash(content) + '.js';
  await writeFile(join(folder, name), content);
  scripts[group] = './data/' + (group ? group + '/' : '') + name;
}
await writeBundle('', [['manifest.json', { json: manifest }], ['results.json', { json: results }]]);
for (const entry of manifest.sequences) {
  const entries = [];
  for (const name of ['manifest.json', 'overview.json.gz', 'features.optimized_uwb.json.gz']) {
    const bytes = await readFile(join(data, entry.name, name));
    entries.push([entry.name + '/' + name, name.endsWith('.gz') ? { gzip: bytes.toString('hex') } : { json: JSON.parse(bytes.toString()) }]);
  }
  await writeBundle(entry.name, entries);
}
await writeFile(join(root, 'source/src/replayCatalog.ts'),
  '// Generated by scripts/build.mjs from local data.\nexport const dataScripts: Record<string, string> = ' + JSON.stringify(scripts, null, 2) + ';\n');

const require = createRequire(import.meta.url);
const tsc = join(dirname(require.resolve('typescript/package.json')), 'bin/tsc');
const check = spawnSync(process.execPath, [tsc, '-p', join(root, 'tsconfig.json')], { stdio: 'inherit' });
if (check.status !== 0) process.exit(check.status ?? 1);

const dist = join(root, 'dist');
await build({
  configFile: false, root: join(root, 'source'), base: './', publicDir: false,
  build: { outDir: dist, emptyOutDir: true, chunkSizeWarningLimit: 900, minify: true,
    lib: { entry: join(root, 'source/src/main.ts'), name: 'OurSlam', formats: ['iife'], fileName: () => 'app.js', cssFileName: 'style' },
  },
});
const js = await readFile(join(dist, 'app.js'));
const css = await readFile(join(dist, 'style.css'));
const jsName = 'app-' + hash(js) + '.js', cssName = 'style-' + hash(css) + '.css';
const assets = join(root, 'assets');
await mkdir(assets, { recursive: true });
for (const name of await readdir(assets)) {
  if (/^(?:index-|dataWorker-|favicon-|app-|style-)/.test(name)) await unlink(join(assets, name));
}
await writeFile(join(assets, jsName), js);
await writeFile(join(assets, cssName), css);
let html = await readFile(join(root, 'source/index.html'), 'utf8');
html = html.replace('</head>', '  <link rel="stylesheet" href="./assets/' + cssName + '">\n</head>')
  .replace(/<script type="module" src="\.\/src\/main\.ts"><\/script>/, '<script defer src="./assets/' + jsName + '"></script>');
await writeFile(join(root, 'index.html'), html);
await cp(data, join(dist, 'data'), { recursive: true });
await cp(assets, join(dist, 'assets'), { recursive: true });
await writeFile(join(dist, 'index.html'), html);
await copyFile(join(root, 'source/favicon.svg'), join(dist, 'favicon.svg'));
await copyFile(join(dist, 'favicon.svg'), join(root, 'favicon.svg'));
console.log('Built ' + manifest.sequences.length + ' sandbox-compatible replay sequences.');
